import { groupByScope } from "@air/domain";
import type { ExportResult, Scope } from "@air/schema";
import type { ExportInput, ExportItem, Exporter } from "./types";

const SCOPE_HEADINGS: Record<Scope, string> = {
  general: "General",
  organization: "Organization",
  personal: "Personal",
  project: "Project",
  experimental: "Experimental",
};

const bullets = (items: readonly string[]) => items.map((i) => `- ${i}`).join("\n");

function slugifyFilename(s: string): string {
  const slug = s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
  return slug || "instructions";
}

export function renderItem(item: ExportItem, headingLevel = 3): string {
  const h = "#".repeat(headingLevel);
  const sub = "#".repeat(Math.min(headingLevel + 1, 6));
  const { activation, instructions, body, tags } = item.content;
  const out: string[] = [];

  out.push(`${h} ${item.displayName}`);
  out.push("");
  out.push(`\`${item.name}\` · v${item.version} · ${item.scope} · ${item.status}`);
  if (item.description) {
    out.push("");
    out.push(item.description);
  }

  const activationBlocks: string[] = [];
  if (activation.when.length) activationBlocks.push(`**Use when:**\n\n${bullets(activation.when)}`);
  if (activation.whenNot.length) activationBlocks.push(`**Do not use when:**\n\n${bullets(activation.whenNot)}`);
  if (activation.requiredContext.length)
    activationBlocks.push(`**Required context:** ${activation.requiredContext.map((c) => `\`${c}\``).join(", ")}`);
  if (activation.preferredContext.length)
    activationBlocks.push(`**Preferred context:** ${activation.preferredContext.map((c) => `\`${c}\``).join(", ")}`);
  if (activationBlocks.length) {
    out.push("", `${sub} Activation`, "", activationBlocks.join("\n\n"));
  }

  if (instructions.length || body.trim()) {
    out.push("", `${sub} Instructions`);
    if (instructions.length) out.push("", bullets(instructions));
    if (body.trim()) out.push("", body.trim());
  }

  if (tags.length) {
    out.push("", `Tags: ${tags.map((t) => `\`${t}\``).join(" ")}`);
  }
  return out.join("\n");
}

/** Generic Markdown Exporter (MVP) */
export class MarkdownExporter implements Exporter {
  readonly format = "markdown" as const;
  readonly label = "Generic Markdown";

  export(input: ExportInput): ExportResult {
    const title = input.project ? `${input.project.name} — AI Instructions` : "AI Instructions";
    const generatedAt = (input.generatedAt ?? new Date()).toISOString();
    const out: string[] = [`# ${title}`, ""];
    out.push(`> Generated by AI Instruction Registry at ${generatedAt}`);
    if (input.project?.description) out.push("", input.project.description);

    if (input.items.length === 0) {
      out.push("", "_No instructions._");
    }

    // 単一Instructionならスコープ見出しは付けない
    if (input.items.length === 1) {
      out.push("", renderItem(input.items[0]!, 2));
    } else {
      for (const group of groupByScope(input.items)) {
        out.push("", `## ${SCOPE_HEADINGS[group.scope]}`);
        for (const item of group.items) out.push("", renderItem(item, 3));
      }
    }

    const base =
      input.project ? slugifyFilename(input.project.name) : input.items.length === 1 ? input.items[0]!.name : "instructions";
    return {
      format: this.format,
      filename: `${base}.md`,
      mimeType: "text/markdown",
      content: out.join("\n") + "\n",
    };
  }
}
