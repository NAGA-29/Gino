import { describe, expect, it } from "vitest";
import { InstructionContentSchema } from "@air/schema";
import { getExporter, type ExportItem } from "../src";

const item = (over: Partial<ExportItem>): ExportItem => ({
  name: "api-design-review",
  displayName: "API Design Review",
  description: "API設計をレビューする。",
  scope: "general",
  status: "published",
  version: "2.1.0",
  content: InstructionContentSchema.parse({
    activation: { when: ["新規APIを設計する"], whenNot: ["UIのみの変更"], requiredContext: ["backend"] },
    instructions: ["REST semanticsを確認する", "HTTP status codeを確認する"],
    tags: ["api"],
  }),
  ...over,
});

describe("MarkdownExporter", () => {
  const generatedAt = new Date("2026-01-01T00:00:00Z");

  it("renders a single instruction", () => {
    const r = getExporter("markdown").export({ items: [item({})], generatedAt });
    expect(r.filename).toBe("api-design-review.md");
    expect(r.content).toMatchInlineSnapshot(`
      "# AI Instructions

      > Generated by AI Instruction Registry at 2026-01-01T00:00:00.000Z

      ## API Design Review

      \`api-design-review\` · v2.1.0 · general · published

      API設計をレビューする。

      ### Activation

      **Use when:**

      - 新規APIを設計する

      **Do not use when:**

      - UIのみの変更

      **Required context:** \`backend\`

      ### Instructions

      - REST semanticsを確認する
      - HTTP status codeを確認する

      Tags: \`api\`
      "
    `);
  });

  it("groups project profile by scope layer", () => {
    const r = getExporter("markdown").export({
      project: { name: "Motion Studio", description: "" },
      items: [item({}), item({ name: "motion-studio", displayName: "Motion Studio Dev", scope: "project" })],
      generatedAt,
    });
    expect(r.filename).toBe("motion-studio.md");
    expect(r.content).toContain("# Motion Studio — AI Instructions");
    expect(r.content.indexOf("## General")).toBeLessThan(r.content.indexOf("## Project"));
    expect(r.content).toContain("### Motion Studio Dev");
  });
});
